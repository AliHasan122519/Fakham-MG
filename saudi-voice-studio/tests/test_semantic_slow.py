def test_semantic_beats_lexical_on_heldout_sentences():
    from svs import analysis, semantic
    texts = [s for ss in TEST.values() for s in ss]
    gold = [e for e, ss in TEST.items() for _ in ss]
    lex = [analysis.detect_emotion(t)["emotion"] for t in texts]
    sem = [max(r["probs"], key=r["probs"].get) for r in semantic.emotion_scores(texts, context=0.0)]
    acc = lambda p: sum(a == b for a, b in zip(p, gold)) / len(gold)
    assert acc(sem) >= 0.70 and acc(sem) > acc(lex) + 0.2


def test_word_sense_accuracy():
    from svs import semantic
    ok = sum(semantic.word_sense(sent, stem)["say"] == truth for stem, sent, truth in SENSE)
    assert ok / len(SENSE) >= 0.85
